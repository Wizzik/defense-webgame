/** The authors of the icons the items use, in the order of ICON_AUTHORS. */
export function usedIconAuthors(): string[] {
  const used = new Set(Object.values(ITEM_ICONS).map((ref) => ref.slice(0, ref.indexOf("/"))));
  return Object.keys(ICON_AUTHORS).filter((a) => used.has(a)).map((a) => ICON_AUTHORS[a]!);
}

/** The file name (without `.svg`) of an icon reference: `"lorc/hood"` -> `"lorc-hood"`. */
export const iconFile = (ref: string): string => ref.replace("/", "-");
